// Builds apps/desktop/ui/icons.svg, a sprite of the Lucide icons the UI uses, and copies the Lucide license beside it.
//
// Usage (Lucide is fetched outside the repo so no node_modules lands here):
//   npm i --prefix <scratch>/lucide lucide-static@1.61.0
//   node scripts/build-icons.mjs <scratch>/lucide/node_modules/lucide-static
//
// To add an icon, add its Lucide name to ICONS below and rerun. Reference it in the UI as icon('name').

const ICONS = [
  'at-sign', 'ban', 'check', 'chevron-down', 'circle-alert', 'clock', 'copy', 'hash', 'house', 'info',
  'key-round', 'log-out', 'message-circle', 'message-square', 'pencil', 'plus', 'send-horizontal',
  'settings', 'shield-minus', 'shield-plus', 'trash-2', 'undo-2', 'user-plus', 'x',
];

import { readFileSync, writeFileSync, copyFileSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pkgDir = resolve(process.argv[2] ?? '');
if (!process.argv[2] || !existsSync(join(pkgDir, 'icons'))) {
  console.error('usage: node scripts/build-icons.mjs <path to lucide-static package>');
  process.exit(1);
}

const STROKE = 'fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"';

const symbols = ICONS.map((name) => {
  const svg = readFileSync(join(pkgDir, 'icons', `${name}.svg`), 'utf8');
  const inner = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/)?.[1];
  if (inner === undefined) throw new Error(`no <svg> body in ${name}.svg`);
  const body = inner.trim().split('\n').map((line) => `    ${line.trim()}`).join('\n');
  return `  <symbol id="i-${name}" viewBox="0 0 24 24" ${STROKE}>\n${body}\n  </symbol>`;
});

const sprite = [
  '<!-- Lucide icons (ISC licence, see icons.LICENSE). Generated by scripts/build-icons.mjs; do not edit. -->',
  '<svg xmlns="http://www.w3.org/2000/svg" style="display:none">',
  ...symbols,
  '</svg>',
  '',
].join('\n');

writeFileSync(join(root, 'apps/desktop/ui/icons.svg'), sprite);
copyFileSync(join(pkgDir, 'LICENSE'), join(root, 'apps/desktop/ui/icons.LICENSE'));
console.log(`wrote ${ICONS.length} symbols to apps/desktop/ui/icons.svg`);
